def build():
    rows = []
    for rule, clauses in CLAUSES.items():
        for index, combination in enumerate(itertools.product(range(3), repeat=3)):
            facts = [['yes','no','unknown'][i] for i in combination]
            sentences = [clauses[k][v] for k, v in enumerate(combination)]
            for variant, order in enumerate(((0,1,2),(2,0,1))):
                text = ('Условный учебный эпизод. ' if variant == 0 else 'Дано описание наблюдения. ')
                text += ' '.join(sentences[i] for i in order)
                rows.append({'id':f'{rule}-train-{index}-{variant}', 'split':'train',
                             'family':f'{rule}-counterfactual-{index}', 'rule_id':rule,
                             'observation':text, 'facts':facts, 'synthetic':True})
        for index, (text, facts) in enumerate(CHALLENGE[rule]):
            rows.append({'id':f'{rule}-challenge-{index}', 'split':'challenge',
                         'family':f'{rule}-natural-{index}', 'rule_id':rule,
                         'observation':text, 'facts':facts, 'synthetic':True})
    for row in rows:
        row['expected_status'] = assess(row['rule_id'], row['facts'])['status']
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    data = ''.join(json.dumps(row, ensure_ascii=False)+'\n' for row in build())
    (args.output/'examples.jsonl').write_bytes(data.encode('utf-8'))
    manifest = {'schema_version':1, 'data_kind':'fictional_public_rule_reasoning',
                'train_examples':324, 'challenge_examples':36,
                'source_url':'https://adilet.zan.kz/rus/docs/V1900019680',
                'verified_on':'2026-10-18', 'sha256':hashlib.sha256(data.encode()).hexdigest(),
                'limitations':['Synthetic author-labeled examples; no human-reviewed bank action labels.',
                               'Challenge shares legal conditions with training; small language-transfer test only.',
                               'Does not measure visual recognition, legal correctness or real-world generalization.']}
    (args.output/'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(json.dumps(manifest))


if __name__ == '__main__':
    main()
